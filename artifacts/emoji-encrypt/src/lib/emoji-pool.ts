const EMOJI_TEST = /\p{Extended_Pictographic}/u;

function buildEmojiPool(): string[] {
  const seen = new Set<string>();

  for (const [start, end] of UNICODE_EMOJI_RANGES) {
    for (let cp = start; cp <= end; cp++) {
      try {
        const emoji = String.fromCodePoint(cp);
        if (EMOJI_TEST.test(emoji)) {
          seen.add(emoji);
        }
      } catch {
        // skip invalid code points
      }
    }
  }

  return Array.from(seen);
}

export const EMOJI_POOL: string[] = buildEmojiPool();

export function shuffleArray<T>(arr: T[]): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export function encodeIndexAsEmojiPair(index: number, pool: string[]): string {
  const base = pool.length;
  const high = Math.floor(index / base) % base;
  const low = index % base;
  return `${pool[high]}${pool[low]}`;
}
